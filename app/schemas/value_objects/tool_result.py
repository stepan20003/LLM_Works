"""Tool result value object capturing the execution outcome of a tool invocation."""

from pydantic import BaseModel, ConfigDict, Field, model_validator
from app.schemas.value_objects.attachment import Attachment
from app.schemas.value_objects.metadata import Metadata


class ToolResult(BaseModel):
    """Represents the immutable structured output resulting from executing a development tool."""

    model_config = ConfigDict(frozen=True, arbitrary_types_allowed=True)

    success: bool = Field(
        ..., description="Indicates whether the tool executed successfully."
    )
    stdout: str = Field(
        default="", description="Standard output stream captured during execution."
    )
    stderr: str = Field(
        default="", description="Standard error stream captured during execution."
    )
    stdout_truncated: bool = Field(
        default=False, description="Indicates if stdout was truncated due to size limits."
    )
    stderr_truncated: bool = Field(
        default=False, description="Indicates if stderr was truncated due to size limits."
    )
    exit_code: int = Field(
        default=0, description="Numeric process exit code."
    )
    execution_time: float = Field(
        default=0.0, ge=0.0, description="Execution duration measured in seconds."
    )
    artifacts: list[Attachment] = Field(
        default_factory=list, description="Files or output artifacts generated by the tool."
    )
    metadata: Metadata = Field(
        default_factory=Metadata, description="Typed execution metadata."
    )

    @model_validator(mode="after")
    def validate_exit_code_consistency(self) -> "ToolResult":
        """Ensure execution success aligns with process exit code."""
        if self.success and self.exit_code != 0:
            raise ValueError(
                f"Tool execution marked successful (success=True) but returned non-zero exit code ({self.exit_code})."
            )
        return self