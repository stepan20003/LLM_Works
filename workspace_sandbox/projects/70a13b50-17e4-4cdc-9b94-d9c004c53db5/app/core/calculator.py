from typing import Optional

class Calculator:
    @staticmethod
    def add(num1: float, num2: float) -> float:
        """
        Returns the sum of two numbers.

        Args:
            num1 (float): The first number.
            num2 (float): The second number.

        Returns:
            float: The sum of num1 and num2.
        """
        return num1 + num2